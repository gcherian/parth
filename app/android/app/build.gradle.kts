// macOS creates ._* metadata files on non-Apple filesystems (like Seagate exFAT).
// This task purges them before aapt processes resources, preventing build failures.
tasks.configureEach {
    if (name.contains("Resources") || name.contains("Assets") || name == "preBuild") {
        doFirst {
            fileTree(rootDir) {
                include("**/_*")
                include("**/._*")
            }.filter { it.name.startsWith("._") }.forEach { it.delete() }
        }
    }
}
